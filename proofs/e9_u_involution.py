from sage.all import *
# DERIVATION MODE. T/2 as involution: what does U do?
# T^2=4I, tr=0 (PROVED E6). So U=T/2 has U^2=I, tr=0.
# Find eigenspaces, relations to volW/H1/H2, geometric meaning.

I2 = matrix(QQ, [[1,0],[0,1]])
X = matrix(QQ, [[0,1],[1,0]])
Z = matrix(QQ, [[1,0],[0,-1]])
Y = matrix(QQ, [[0,-1],[1,0]])
e = [X.tensor_product(I2), Y.tensor_product(I2), Z.tensor_product(X), Z.tensor_product(Y)]
I4 = identity_matrix(QQ,4)
Omega = e[0]*e[1]*e[2]*e[3]
E = [e[mu].tensor_product(I4) for mu in range(4)] + [Omega.tensor_product(e[nu]) for nu in range(4)]
I16 = identity_matrix(QQ,16)
S = lambda mu,nu: (E[mu]*E[nu] - E[nu]*E[mu])/2

print("=== U = T/2, where T=S04*S15-S05*S14 ===")
T = S(0,4)*S(1,5) - S(0,5)*S(1,4)
U = T/2
print(f"U^2 = I? {(U*U - I16).is_zero()}")
print(f"tr(U) = {U.trace()}")

print()
print("=== Eigenvalues ===")
cp = U.charpoly()
print(f"charpoly: {cp.factor()}")
# Expect (x-1)^8 (x+1)^8 since tr=0 and U^2=I.

print()
print("=== Relations ===")
volW = E[0]*E[1]*E[4]*E[5]
H1 = S(0,1); H2 = S(4,5)
print(f"[U,volW]=0? {(U*volW-volW*U).is_zero()}")
print(f"[U,H1]=0? {(U*H1-H1*U).is_zero()}")
print(f"[U,H2]=0? {(U*H2-H2*U).is_zero()}")
# U is built from mixed generators. Does it commute with unmixed?
print(f"[U,S01]=0? {(U*S(0,1)-S(0,1)*U).is_zero()} (S01 is H1, already checked)")

print()
print("=== Is U in the algebra generated by Cl(2,2)? ===")
# U is a product of S_mn, which are in the enveloping algebra.
# Is U itself in Cl(2,2) (the 16-dim algebra spanned by products of E_mu)?
# Cl(2,2) has dimension 16 (as vector space: 1, E_mu, E_mu E_nu, ...).
# U is 16x16. Check if U is in the span.
# Build basis of Cl(2,2) as matrices.
basis = [I16]
for mu in [0,1,4,5]:
    basis.append(E[mu])
for i,mu in enumerate([0,1,4,5]):
    for nu in [0,1,4,5][i+1:]:
        basis.append(E[mu]*E[nu])
for i,mu in enumerate([0,1,4,5]):
    for j,nu in enumerate([0,1,4,5]):
        for k,rh in enumerate([0,1,4,5]):
            if i<j<k:
                basis.append(E[mu]*E[nu]*E[rh])
basis.append(E[0]*E[1]*E[4]*E[5])
print(f"Cl(2,2) basis size: {len(basis)} (expect 16)")
# Check linear independence and if U is in span.
B = matrix(QQ, [M.list() for M in basis]).transpose()
print(f"rank: {B.rank()}")
v = vector(QQ, U.list())
try:
    c = B.solve_right(v)
    print(f"U IS in Cl(2,2). Coeffs (first 5): {list(c[:5])}")
except:
    print("U is NOT in Cl(2,2) span (not a linear combo).")

print()
print("=== Geometric meaning ===")
print("U^2=I, tr=0 => U is a reflection (involution) with 8+8 eigenspaces.")
print("It commutes with volW, H1, H2.")
print("U is built from the INTERPLAY (mixed generators).")
print("So U is the 'reflection across the interplay' — it swaps something")
print("while preserving the two-worlds structure (commutes with volW).")


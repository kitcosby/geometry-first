from sage.all import *
# The interplay: mixed Spin(2,2) generators coupling plane A=(E0,E1) and B=(E4,E5).
# What algebra do they generate? What do they do?

I2 = matrix(QQ, [[1,0],[0,1]])
X = matrix(QQ, [[0,1],[1,0]])
Z = matrix(QQ, [[1,0],[0,-1]])
Y = matrix(QQ, [[0,-1],[1,0]])
e = [X.tensor_product(I2), Y.tensor_product(I2), Z.tensor_product(X), Z.tensor_product(Y)]
I4 = identity_matrix(QQ,4)
Omega = e[0]*e[1]*e[2]*e[3]
E = [e[mu].tensor_product(I4) for mu in range(4)] + [Omega.tensor_product(e[nu]) for nu in range(4)]

print("=== Plane A = span{E0,E1}, Plane B = span{E4,E5} ===")
print("Unmixed: S01 (in A), S45 (in B).")
print("Mixed (interplay): S04, S05, S14, S15.")

S = lambda mu,nu: (E[mu]*E[nu] - E[nu]*E[mu])/2
mixed = [S(0,4), S(0,5), S(1,4), S(1,5)]
unmixed = [S(0,1), S(4,5)]

print()
print("=== What do mixed generators do to the planes? ===")
# Take a vector in A (e.g., E0), apply mixed S04, see where it goes.
# [S04, E0] = ? Should have components in B.
vecs = [M.list() for M in E]
Bmat = matrix(QQ, vecs).transpose()
for (mu,nu),name in [((0,4),"S04"),((0,5),"S05"),((1,4),"S14"),((1,5),"S15")]:
    Smn = S(mu,nu)
    print(f"{name}:")
    for rho in [0,1,4,5]:
        comm = Smn*E[rho] - E[rho]*Smn
        v = vector(QQ, comm.list())
        c = Bmat.solve_right(v)
        nz = [(s,int(c[s])) for s in range(8) if c[s]!=0]
        # Classify: in A (0,1), in B (4,5), or outside
        inA = [s for s,_ in nz if s in [0,1]]
        inB = [s for s,_ in nz if s in [4,5]]
        out = [s for s,_ in nz if s not in [0,1,4,5]]
        print(f"  [{name},E{rho}] -> A:{inA} B:{inB} out:{out}")

print()
print("=== Algebra generated by mixed ===")
# Compute commutators of mixed generators. What do we get?
print("Commutators [mixed_i, mixed_j]:")
import itertools
for (i,j) in itertools.combinations(range(4),2):
    names=["S04","S05","S14","S15"]
    c = mixed[i]*mixed[j] - mixed[j]*mixed[i]
    # Express in basis of all 6 S22 + identity?
    # Just check if it's in span of {S01,S45,mixed} or gives something new.
    # For now, check trace and if it's zero.
    print(f"  [{names[i]},{names[j]}]: tr={c.trace()}, zero? {c.is_zero()}")

print()
print("=== Do mixed preserve W? ===")
# W = span{E0,E1,E4,E5}. Do mixed S_mn preserve W as a set?
# We saw above they map E_rho (rho in W) to combos. Check if all stay in W.
print("From above: if 'out' is empty for all, then W is preserved.")
print("(This would mean Spin(2,2) preserves W, which we know since W is the vector rep.)")


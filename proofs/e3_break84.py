from sage.all import *
# 8->4 breaking: weights of the 8-vector under Cartan, then find natural 4-dim.

I2 = matrix(QQ, [[1,0],[0,1]])
X = matrix(QQ, [[0,1],[1,0]])
Z = matrix(QQ, [[1,0],[0,-1]])
Y = matrix(QQ, [[0,-1],[1,0]])
e = [X.tensor_product(I2), Y.tensor_product(I2), Z.tensor_product(X), Z.tensor_product(Y)]
I4 = identity_matrix(QQ,4)
Omega = e[0]*e[1]*e[2]*e[3]
E = [e[mu].tensor_product(I4) for mu in range(4)] + [Omega.tensor_product(e[nu]) for nu in range(4)]

print("=== Cartan generators H1..H4 ===")
H = [(E[0]*E[1]-E[1]*E[0])/2, (E[2]*E[3]-E[3]*E[2])/2,
     (E[4]*E[5]-E[5]*E[4])/2, (E[6]*E[7]-E[7]*E[6])/2]
for i,Hm in enumerate(H):
    print(f"H{i+1} = S_({2*i},{2*i+1}), H^2 = {(Hm*Hm)[0,0]}*I (scalar: {all((Hm*Hm)[a,b]==0 for a in range(16) for b in range(16) if a!=b)})")

print()
print("=== Adjoint action of Cartan on the 8-vector {E_rho} ===")
# [H_i, E_rho] = sum_sigma M^{(i)}_{rho,sigma} E_sigma
# Compute the 8x8 matrices M^{(i)} (the vector representation matrices)
vecs = [M.list() for M in E]
B = matrix(QQ, vecs).transpose()
Mmat = []
for i,Hm in enumerate(H):
    M8 = matrix(QQ, 8, 8)
    for rho in range(8):
        comm = Hm*E[rho] - E[rho]*Hm
        v = vector(QQ, comm.list())
        c = B.solve_right(v)
        for sigma in range(8):
            M8[rho,sigma] = c[sigma]
    Mmat.append(M8)
    print(f"M^({i+1}) (H_{i+1} action on vector):")
    print(M8)
    print()

print("=== Simultaneous diagonalization? ===")
# The M^{(i)} are 8x8. Do they commute? (They should, since H_i commute.)
for i in range(4):
    for j in range(i+1,4):
        c = Mmat[i]*Mmat[j] - Mmat[j]*Mmat[i]
        print(f"[M^({i+1}), M^({j+1})] = 0? {c.is_zero()}")

print()
print("=== Weights: simultaneous eigenvectors over QQbar ===")
# Since they commute, find common eigenvectors. Work over QQbar.
# Actually, the M^{(i)} may not be diagonalizable over QQ. Let's get charpolys.
for i in range(4):
    cp = Mmat[i].charpoly()
    print(f"charpoly M^({i+1}): {cp.factor()}")

print()
print("=== Natural 4-dim? Look for invariant 4-plane ===")
# The vector rep matrices M^{(i)}. Find all invariant subspaces.
# Simplest: check if span{E_0..E_3} or span{E_4..E_7} is invariant under ALL S_mn.
# We already know mixed S_{mu,nu} (mu<4<=nu) mix them. So no.
# Instead: find the weight decomposition. The 8 weights under Cartan.
# Compute over QQbar: simultaneous eigenspaces.

# Use the fact that H_i^2 = +/-I. So eigenvalues are +/-1 or +/-i.
# Let's diagonalize over QQbar.
Hbar = [M.change_ring(QQbar) for M in Mmat]
# Find common eigenvector by intersecting eigenspaces
# Start with eigenspaces of M^(1)
eig1 = Hbar[0].eigenspaces_right()
print(f"M^(1) eigenspaces: {[(ev, V.dimension()) for ev,V in eig1]}")
# For each, restrict others and continue
# This is tedious; instead, note the structure from charpolys.

print()
print("=== Branching: try SO(3,1) subgroup ===")
# SO(4,4) -> SO(3,1) x SO(1,3)? The 8-vector branches.
# Actually, let's look for a 4-dim SUBMODULE under a subalgebra.
# Take the subalgebra generated by S_mn for mu,nu in {0,1,2,3} (first SO(4)).
# Does it preserve a 4-dim subspace of the 8-vector?
# From the fit: S_(0,1) acts only on E_0,E_1. S_(2,3) acts only on E_2,E_3.
# So the subalgebra <S_01,S_02,...,S_23> (SO(4) on indices 0..3):
# Let's see its action on the 8-vector.
print("Action of <S_mn : 0<=mu<nu<=3> on {E_rho}:")
# From e2 fit, S_(0,1) only touches E_0,E_1. By symmetry, S_mn for mu,nu<=3
# only touches E_0..E_3. So span{E_0..E_3} IS invariant under this SO(4)!
# And span{E_4..E_7} is also invariant (untouched).
# So under SO(4)xSO(4) (the maximal compact), 8 -> 4+4.
# The 4+4 are the two SO(4) vectors.

# But we want SO(3,1), not SO(4). SO(3,1) is non-compact.
# The issue: our E_mu are fixed. The SO(4)xSO(4) 4+4 is natural
# (it's just the index split). But is it PHYSICAL? The metric on
# indices 0..3: E_0^2..E_3^2 = ? (from e2: need to check)
# If E_0^2=+1 and E_1^2=E_2^2=E_3^2=-1 (or similar), then span{E_0..E_3}
# has Lorentz signature (3,1) or (1,3), and it's a spacetime candidate!

print()
print("=== Metric on the 4+4 split ===")
for mu in range(8):
    d = (E[mu]*E[mu])[0,0]
    print(f"E_{mu}^2 = {d}")


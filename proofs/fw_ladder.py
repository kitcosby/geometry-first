import sys, time
from sage.rings.qqbar import QQbar
from sage.matrix.constructor import matrix

# NOTE on field choice: this Sage install has a broken numpy, and
# both number-field shortcuts hit it (NumberField(embedding=...)
# imports sage.rings.polynomial.real_roots; the QQbar->field
# conversion utility fails its internal hom check). So all
# arithmetic stays in QQbar, whose elements from Q(sqrt2,sqrt3)
# are exact and whose real elements compare exactly -- enough for
# the Killing pivot signs.
K = QQbar
s2 = K(2).sqrt(); s3 = K(3).sqrt(); s6 = s2 * s3
print('QQbar ready; sqrt2, sqrt3, sqrt6 exact', flush=True)

TRIG = {
 15: ((s6 - s2) / 4, (s6 + s2) / 4), 30: (K(1) / 2, s3 / 2),
 45: (s2 / 2, s2 / 2), 60: (s3 / 2, K(1) / 2),
 75: ((s6 + s2) / 4, (s6 - s2) / 4),
 105: ((s6 + s2) / 4, -(s6 - s2) / 4), 120: (s3 / 2, -K(1) / 2),
 135: (s2 / 2, -s2 / 2), 150: (K(1) / 2, -s3 / 2),
 165: ((s6 - s2) / 4, -(s6 + s2) / 4)}
DEGS = [15, 30, 45, 60, 75, 105, 120, 135, 150, 165]

def ops(deg):
    s, c = TRIG[deg]
    absc = c if deg < 90 else -c
    srx = 1 / s + c / s
    sxp = 1 / srx
    cxp = 1 / absc + s / c
    crx = 1 / cxp
    urx = srx - crx
    uxp = cxp - sxp
    FW = 1 / urx + 1 / uxp
    return (srx, sxp, cxp, crx, urx, uxp, FW, 2 * s * c, c * c - s * s)

for d in DEGS:
    o = ops(d)
    assert o[6] == (K(1) if d < 90 else K(-1)), ('FW check', d)
    a2 = o[7] if d < 90 else -o[7]
    assert o[4] * o[5] == 4 / a2, ('SINPROD check', d)
print('sample self-checks OK: FW = sgn(sin2x), urx*uxp = 4/|sin2x| at all 10 samples', flush=True)

def build(deg, n, kind):
    srx, sxp, cxp, crx, urx, uxp, FW, sin2, cos2 = ops(deg)
    M = [[K(0) for _ in range(n)] for _ in range(n)]
    if kind == 'FW':
        diag = [urx, uxp, FW] + [K(0)] * (n - 3)
    else:
        diag = [sin2 if i % 2 == 1 else cos2 for i in range(1, n)]
        diag.append(-sum(diag))
    for i in range(n):
        M[i][i] = diag[i]
    for i in range(1, n):
        M[i - 1][i] = srx if i % 2 == 1 else crx
        M[i][i - 1] = cxp if i % 2 == 1 else sxp
    if kind == 'FW':
        M[0][n - 1] = cos2; M[n - 1][0] = sin2
    else:
        M[0][n - 1] = FW; M[n - 1][0] = FW
    Mx = matrix(K, n, n, [M[i][j] for i in range(n) for j in range(n)])
    if kind == 'FW':
        tr = Mx.trace()
        Mx = Mx - (tr / n) * matrix(K, n, n,
            [K(1) if i == j else K(0) for i in range(n) for j in range(n)])
    return Mx

class Span:
    def __init__(self, L):
        self.L = L; self.rows = []; self.piv = []
    def try_add(self, v):
        v = list(v)
        for r, p in zip(self.rows, self.piv):
            f = v[p]
            if f != 0:
                v = [a - f * b for a, b in zip(v, r)]
        p = -1
        for i, a in enumerate(v):
            if a != 0:
                p = i; break
        if p < 0:
            return False
        f = v[p]
        v = [a / f for a in v]
        for i2 in range(len(self.rows)):
            f2 = self.rows[i2][p]
            if f2 != 0:
                self.rows[i2] = [a - f2 * b for a, b in zip(self.rows[i2], v)]
        self.rows.append(v); self.piv.append(p)
        return True
    def dim(self):
        return len(self.rows)
    def mat(self, i, n):
        return matrix(K, n, n, self.rows[i])

def flat(M, n):
    return [M[i, j] for i in range(n) for j in range(n)]

def closure(gens, n):
    B = Span(n * n)
    for g in gens:
        B.try_add(flat(g, n))
    span0 = B.dim()
    changed = True
    while changed:
        changed = False
        cur = [B.mat(i, n) for i in range(B.dim())]
        for i in range(len(cur)):
            for j in range(i + 1, len(cur)):
                if B.try_add(flat(cur[i] * cur[j] - cur[j] * cur[i], n)):
                    changed = True
    return B, span0

def killing_signature(B, n):
    d = B.dim()
    mats = [B.mat(i, n) for i in range(d)]
    A = [[2 * n * (mats[i] * mats[j]).trace() for j in range(d)] for i in range(d)]
    pos = neg = zer = 0
    for k in range(d):
        if A[k][k] == 0:
            sw = -1
            for i in range(k + 1, d):
                if A[i][i] != 0:
                    sw = i; break
            if sw >= 0:
                for r in range(d):
                    A[r][k], A[r][sw] = A[r][sw], A[r][k]
                for cc in range(d):
                    A[k][cc], A[sw][cc] = A[sw][cc], A[k][cc]
            else:
                add = -1
                for i in range(k + 1, d):
                    if A[i][k] != 0:
                        add = i; break
                if add < 0:
                    zer += 1
                    continue
                for cc in range(d):
                    A[k][cc] = A[k][cc] + A[add][cc]
                for rr in range(d):
                    A[rr][k] = A[rr][k] + A[rr][add]
        piv = A[k][k]
        e = piv
        if e > 0:
            pos += 1
        elif e < 0:
            neg += 1
        else:
            zer += 1
        if piv != 0:
            for i in range(k + 1, d):
                f = A[i][k]
                if f != 0:
                    f = f / piv
                    for j in range(k, d):
                        A[i][j] = A[i][j] - f * A[k][j]
    return (pos, neg, zer)

def main():
    t0 = time.time()
    samples = [build(d, N, KIND) for d in DEGS]
    B4 = Span(N * N)
    for g in samples[:4]:
        B4.try_add(flat(g, N))
    print('span of E96 sample subset (15,30,45,60):', B4.dim(), flush=True)
    B, span0 = closure(samples, N)
    print('sample span (10 samples):', span0, flush=True)
    print('closure dim:', B.dim(), ' target:', N * N - 1, flush=True)
    traceless = all(B.mat(i, N).trace() == 0 for i in range(B.dim()))
    print('all basis matrices traceless:', traceless, flush=True)
    if B.dim() == N * N - 1 and traceless:
        sig = killing_signature(B, N)
        print('Killing signature (pos, neg, zero):', sig,
              ' expected split:', (N * (N + 1) // 2 - 1, N * (N - 1) // 2, 0), flush=True)
    print('elapsed %.1fs' % (time.time() - t0), flush=True)
    print('RUN DONE', KIND, N, flush=True)

main()

from sage.all import *
# Follow the (2,2): what lives on W = span{E_0,E_1,E_4,E_5}?
# No (3,1) target. Just: what IS this 4-plane?

I2 = matrix(QQ, [[1,0],[0,1]])
X = matrix(QQ, [[0,1],[1,0]])
Z = matrix(QQ, [[1,0],[0,-1]])
Y = matrix(QQ, [[0,-1],[1,0]])
e = [X.tensor_product(I2), Y.tensor_product(I2), Z.tensor_product(X), Z.tensor_product(Y)]
I4 = identity_matrix(QQ,4)
Omega = e[0]*e[1]*e[2]*e[3]
E = [e[mu].tensor_product(I4) for mu in range(4)] + [Omega.tensor_product(e[nu]) for nu in range(4)]

print("=== W = span{E_0,E_1,E_4,E_5}, signature (+,-,+,-) ===")
W_idx = [0,1,4,5]
for mu in W_idx:
    print(f"E_{mu}^2 = {(E[mu]*E[mu])[0,0]}")

print()
print("=== Spin(2,2) generators (S_mn for mu,nu in W) ===")
S22 = {}
for i,mu in enumerate(W_idx):
    for nu in W_idx[i+1:]:
        S22[(mu,nu)] = (E[mu]*E[nu] - E[nu]*E[mu])/2
print(f"{len(S22)} generators (dim of so(2,2) = 6, expect 6)")
# so(2,2) has dimension 6. C(4,2)=6. Good.

print()
print("=== How does the 16 decompose under Spin(2,2)? ===")
# The 16-dim spinor S. Restrict to the subalgebra generated by S22.
# Find invariant subspaces, or compute the commutant.
# Actually: Cl(2,2) gen by E_0,E_1,E_4,E_5. Cl(2,2) ~= M(4,R).
# The 16 should be 4 copies of the 4-dim pinor, OR have a natural tensor structure.
# Let's find the commutant of {E_0,E_1,E_4,E_5} in M(16,QQ).
print("Commutant of {E_0,E_1,E_4,E_5}:")
rows=[]
I16=identity_matrix(QQ,16)
for mu in W_idx:
    K = E[mu].transpose().tensor_product(I16) - I16.tensor_product(E[mu])
    rows.append(K)
M = block_matrix([[r] for r in rows])
ns = M.right_kernel()
d = ns.dimension()
print(f"  dim = {d}")
print(f"  (If Cl(2,2)~=M(4,R) acts, commutant should be M(4,R), dim 16.)")

print()
print("=== Null structure of (2,2) ===")
print("Metric diag(+1,-1,+1,-1) on basis (E_0,E_1,E_4,E_5).")
print("Null vectors v=(a,b,c,d): a^2 - b^2 + c^2 - d^2 = 0.")
print("E.g., (1,1,0,0): 1-1=0 NULL. (1,0,1,0): 1+1=2 not null.")
print("     (1,1,1,1): 1-1+1-1=0 NULL. (1,0,0,1): 1-1=0 NULL.")
print("Null 2-planes: span{(1,1,0,0), (0,0,1,1)}: check...")
print("  (1,1,0,0): null. (0,0,1,1): 0-0+1-1=0 null. Orthogonal? (1,1,0,0).(0,0,1,1)=0. Yes.")
print("  So span{(1,1,0,0),(0,0,1,1)} is a null 2-plane (totally null).")
print("In (2,2), maximal null subspaces are 2-dim (not 1-dim as in (3,1)).")
print("There are TWO families (alpha and beta planes), swapped by orientation.")

print()
print("=== Volume element of W ===")
volW = E[0]*E[1]*E[4]*E[5]
print(f"volW^2 = {(volW*volW)[0,0]} (scalar? {all((volW*volW)[a,b]==0 for a in range(16) for b in range(16) if a!=b)})")
print(f"volW trace = {volW.trace()}")
# Check if volW anticommutes with E_mu for mu in W
for mu in W_idx:
    ac = volW*E[mu] + E[mu]*volW
    print(f"  {{volW, E_{mu}}} = 0? {ac.is_zero()}")

print()
print("=== Self-dual 2-forms (Hodge star, *^2=+1 in (2,2)) ===")
print("In (2,2), *^2=+1 on 2-forms, so Lambda^2 = Lambda^2_+ (+) Lambda^2_- (real split).")
print("This is DIFFERENT from (3,1) where *^2=-1 (needs complexification).")

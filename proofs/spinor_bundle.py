#!/usr/bin/env python3
"""
The spinor bundle over OG+(5,10) = Spin(10)/U(5), built exactly.

The homogeneous spinor bundle is determined by (G, H, isotropy
representation). The isotropy representation and its branching are
the PROVED output of su5_stabilizer.py (imported here as an input,
re-solved where cheap). What THIS build adds, all exact over Q(i):

  1. The reductive complement m of h = u(5) in so(10): the real
     so(10) elements whose adapted-basis A-block vanishes.
     dim_R m = 20, [h, m] subset m (reductive), [m, m] subset h
     (Hermitian symmetric: OG+ = SO(10)/U(5) is type DIII), and
     h (+) m = so(10). m is the tangent-space model of OG+ at the
     basepoint; dim_R 20 = dim_C 10 matches the orbit build.
  2. Complexification: m_C = n (+) n-bar, where n = the B-block
     radical of the orbit build's parabolic. The isotropy action
     on n is the Lambda^2 action in B-matrix coordinates:
     ad(diag(A, -A^T)) sends B to A B + B A^T exactly.
  3. Descent: the centre circle generated by Z (A(Z) = -i I)
     closes at 2 pi on vectors (exp = +I_10) but at 4 pi on
     spinors (rho(Z) diagonal with eigenvalues in i*{+-1/2, +-3/2,
     +-5/2}, so exp(2 pi rho(Z)) = -I_32, the covering kernel).
     The isotropy representation therefore does NOT descend to
     SO(10)'s U(5): the bundle is a genuine Spin bundle.
  4. The tautological line bundle L (fiber = the pure spinor line)
     has isotropy character mu = (1/2) tr A; its Z-weight -5/2 is
     the singlet piece of the spinor bundle.

Controls (per symbolic_checker_validation):
  TRUE  control: {gamma_1, gamma_2} = 0 accepted; the explicit
                 B = C element below IS in m.
  FALSE control: gamma_1 gamma_2 - gamma_2 gamma_1 rejected as 0;
                 E_{0,2} is NOT in m (its A-block is nonzero).
"""
import sys
from sympy import (Matrix, eye, zeros, I, Rational, kronecker_product,
                   re as Re, im as Im)

PASS = 0
FAIL = 0
FAILURES = []

def check(name, cond):
    global PASS, FAIL
    if cond:
        PASS += 1
        print(f"  PASS  {name}")
    else:
        FAIL += 1
        FAILURES.append(name)
        print(f"  FAIL  {name}")

def is_zero(M):
    return all(x == 0 for x in M)

def eq(A, B):
    return is_zero(A - B)

# ---------------------------------------------------------------- gammas
s1 = Matrix([[0, 1], [1, 0]])
s2 = Matrix([[0, -I], [I, 0]])
s3 = Matrix([[1, 0], [0, -1]])
gam = [s1, s2]
while gam[0].rows < 32:
    n = gam[0].rows
    gam = [kronecker_product(g, s3) for g in gam] + \
          [kronecker_product(eye(n), s1), kronecker_product(eye(n), s2)]
G = gam
I32 = eye(32)

print("== checker controls ==")
check("TRUE control: {g1,g2} = 0 accepted", eq(G[0]*G[1] + G[1]*G[0], zeros(32)))
check("FALSE control: g1 g2 - g2 g1 rejected as 0",
      not is_zero(G[0]*G[1] - G[1]*G[0]))

prod = I32
for a in range(10):
    prod = prod * G[a]
Gamma = I * prod
minus_idx = [n for n in range(32) if Gamma[n, n] == -1]
pos0 = minus_idx.index(0)
pairs = [(a, b) for a in range(10) for b in range(a+1, 10)]
Sig = {p: (G[p[0]]*G[p[1]] - G[p[1]]*G[p[0]]) * Rational(1, 4) for p in pairs}
SigM = {p: Sig[p].extract(minus_idx, minus_idx) for p in pairs}

def avec(k, sign):
    v = zeros(10, 1)
    v[2*k] = Rational(1, 2)
    v[2*k+1] = sign * I * Rational(1, 2)
    return v
Wa = [avec(k, +1) for k in range(5)]
Wp = [avec(k, -1) for k in range(5)]
Pa = Matrix.hstack(*(Wa + Wp))
PaInv = Pa.inv()
E = {}
for (a, b) in pairs:
    M = zeros(10); M[a, b] = 1; M[b, a] = -1
    E[(a, b)] = M
Yhat = {p: PaInv * E[p] * Pa for p in pairs}

def real_nullspace(equations):
    """equations: list of (row_fn) -- here we pass a complex matrix
    whose rows are linear forms in the 45 real unknowns."""
    rows = []
    for row in equations:
        rows.append([Re(x) for x in row])
        rows.append([Im(x) for x in row])
    return Matrix(rows).nullspace()

# ------------------------------------------------- stabiliser (input, re-solved)
print("== stabiliser h (proved input, re-solved) ==")
eqs = []
for (r, s) in [(r, s) for r in range(5) for s in range(5, 10)] + \
              [(r, s) for r in range(5, 10) for s in range(5)]:
    eqs.append([Yhat[p][r, s] for p in pairs])
stab = real_nullspace(eqs)
check("dim h = 25", len(stab) == 25)
Ys, Ahat, mu = [], [], []
for cvec in stab:
    Y = sum((cvec[j] * E[p] for j, p in enumerate(pairs)), zeros(10))
    A = (PaInv * Y * Pa)[:5, :5]
    R = sum((cvec[j] * SigM[p] for j, p in enumerate(pairs)), zeros(16))
    Ys.append(Y); Ahat.append(A); mu.append(R[pos0, pos0])

print("== the complement m ==")
eqsA = [[Yhat[p][r, s] for p in pairs] for r in range(5) for s in range(5)]
mspace = real_nullspace(eqsA)
check("dim_R m = 20 (A-block = 0 inside real so(10))", len(mspace) == 20)
Ms = [sum((cv[j] * E[p] for j, p in enumerate(pairs)), zeros(10))
      for cv in mspace]
# controls: explicit B = C element in, E_{0,2} out
B0 = zeros(5); B0[0, 1] = 1; B0[1, 0] = -1
Yh0 = zeros(10); Yh0[:5, 5:] = B0; Yh0[5:, :5] = B0
Y0m = Pa * Yh0 * PaInv
check("TRUE control element: real and Pa-form as expected",
      all(Im(Y0m[r, c]) == 0 for r in range(10) for c in range(10)))
Vall = Matrix.hstack(*[Y.reshape(100, 1) for Y in Ys + Ms])
def in_span_m(Y):
    Vm = Matrix.hstack(*[M.reshape(100, 1) for M in Ms])
    return Vm.rank() == Matrix.hstack(Vm, Y.reshape(100, 1)).rank()
Y0m_r = Matrix(10, 10, lambda r, c: Re(Y0m[r, c]))
check("TRUE control: the B = C element is in m", in_span_m(Y0m_r))
check("FALSE control: E_{0,2} is NOT in m", not in_span_m(E[(0, 2)]))
check("h (+) m spans so(10) (rank 45)", Vall.rank() == 45)

print("== reductive + Hermitian symmetric brackets ==")
piv = Vall.T.rref()[1]
Vp = Vall.extract(list(piv), list(range(45)))
VpInv = Vp.inv()
def coords(Y):
    return VpInv * Y.reshape(100, 1).extract(list(piv), [0])
ok_hm = ok_mm = True
for i in range(25):
    for j in range(20):
        cf = coords(Ys[i]*Ms[j] - Ms[j]*Ys[i])
        if any(cf[t] != 0 for t in range(25)):
            ok_hm = False
for i in range(20):
    for j in range(i+1, 20):
        cf = coords(Ms[i]*Ms[j] - Ms[j]*Ms[i])
        if any(cf[t] != 0 for t in range(25, 45)):
            ok_mm = False
check("[h, m] subset m for all 25 x 20 basis pairs", ok_hm)
check("[m, m] subset h for all basis pairs (Hermitian symmetric)", ok_mm)

print("== complexification: m_C = n (+) n-bar ==")
def proj_rank(block_rows, block_cols, mats):
    vecs = []
    for M in mats:
        Yh = PaInv * M * Pa
        blk = Yh.extract(block_rows, block_cols)
        vecs.append([Re(blk[r, c]) for r in range(blk.rows)
                     for c in range(blk.cols)] +
                    [Im(blk[r, c]) for r in range(blk.rows)
                     for c in range(blk.cols)])
    return Matrix(vecs).rank() // 2   # complex rank via doubled real rank
check("B-projection of m_C spans Lambda^2 (complex rank 10)",
      proj_rank(list(range(5)), list(range(5, 10)), Ms) == 10)
check("C-projection of m_C spans Lambda^2 (complex rank 10)",
      proj_rank(list(range(5, 10)), list(range(5)), Ms) == 10)
check("every m element has A-block 0 (by construction, asserted)",
      all(is_zero((PaInv * M * Pa)[:5, :5]) for M in Ms))

print("== tangent isotropy: ad on n is the Lambda^2 action ==")
skew_units = []
for a in range(5):
    for b in range(a+1, 5):
        U = zeros(5); U[a, b] = 1; U[b, a] = -1
        skew_units.append(U)
radical = []
for U in skew_units:
    for sc in (1, I):
        Yh = zeros(10); Yh[:5, 5:] = sc * U
        radical.append((sc * U, Pa * Yh * PaInv))
okad = True
for j in range(25):
    Dj = Ys[j]
    Aj = Ahat[j]
    for (B, NB) in radical:
        comm = Dj * NB - NB * Dj
        Yh = PaInv * comm * Pa
        if not is_zero(Yh[:5, :5]) or not is_zero(Yh[5:, :]) or \
           not eq(Yh[:5, 5:], Aj * B + B * Aj.T):
            okad = False
check("ad(D) B-block = A B + B A^T, other blocks 0 (25 x 20)", okad)

print("== descent: Spin bundle, not an SO bundle ==")
y0 = zeros(45, 1)
for k in range(5):
    y0[pairs.index((2*k, 2*k+1))] = 1
Y0v = sum((y0[j] * E[p] for j, p in enumerate(pairs)), zeros(10))
check("Y0 is central in h (brackets with all basis elements vanish)",
      all(is_zero(Y0v * Ys[j] - Ys[j] * Y0v) for j in range(25)))
Zv = -Y0v
Zh = PaInv * Zv * Pa
check("A(Z) = -i I and D(Z) = +i I in adapted basis",
      eq(Zh[:5, :5], -I * eye(5)) and eq(Zh[5:, 5:], I * eye(5)))
rhoZ32 = sum((-y0[j] * Sig[p] for j, p in enumerate(pairs)), zeros(32))
check("rho(Z) diagonal on the 32",
      all(rhoZ32[a, b] == 0 for a in range(32) for b in range(32) if a != b))
halves = {I * Rational(k, 2) for k in (-5, -3, -1, 1, 3, 5)}
check("rho(Z) eigenvalues all in i*{+-1/2, +-3/2, +-5/2} "
      "=> exp(2 pi rho(Z)) = -I_32, exp(2 pi Z)_vec = +I_10",
      all(rhoZ32[n, n] in halves for n in range(32)))

print("== tautological line bundle ==")
check("line character mu = (1/2) tr A on all 25 (fiber of L)",
      all(mu[j] == Rational(1, 2) * Ahat[j].trace() for j in range(25)))
# Z-weight of the line = singlet charge
zidx = None
for j in range(25):
    pass
rhoZ16 = rhoZ32.extract(minus_idx, minus_idx)
check("Z-weight of L (rho(Z) on e_0) = -5i/2 = singlet charge",
      rhoZ16[pos0, pos0] == Rational(-5, 2) * I)

print()
print(f"RESULT: {PASS} PASS, {FAIL} FAIL")
if FAILURES:
    print("failures:", FAILURES)
    sys.exit(1)

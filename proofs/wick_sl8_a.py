import numpy as np
rt3 = np.sqrt(3)
a = np.array([2+rt3, 2-rt3, rt3, rt3/3, 2+2*rt3/3, 3/4-rt3/4, -2+2*rt3, 1/4+rt3/4])  # operators at 30deg
def E(i,j):
    M = np.zeros((8,8), dtype=complex); M[i,j] = 1; return M
# Wick-rotated cycle generators: W_i = antisym part + i * sym part of X_i = a_i E_{i,i+1}.
W = []
for i in range(8):
    Xi = a[i]*E(i, (i+1) % 8)
    anti = (Xi - Xi.T)/2; sym = (Xi + Xi.T)/2
    Wi = anti + 1j*sym
    W.append(Wi)
print('all W_i anti-Hermitian:', all(np.allclose(w + w.conj().T, 0) for w in W))
print('all W_i traceless:', all(abs(np.trace(w)) < 1e-12 for w in W))

def real_vec(M): return np.concatenate([M.real.flatten(), M.imag.flatten()])
def rank_of(mats):
    if not mats: return 0
    return np.linalg.matrix_rank(np.array([real_vec(m) for m in mats]).T, tol=1e-7)
G = list(W); r = rank_of(G)
for _ in range(14):
    if r >= 63: break
    cur = list(G); added = False
    for i in range(len(cur)):
        for j in range(i+1, len(cur)):
            comm = cur[i]@cur[j] - cur[j]@cur[i]
            if rank_of(G+[comm]) > r:
                G.append(comm); r = rank_of(G); added = True
                if r >= 63: break
        if r >= 63: break
    if not added: break
print('real dim generated by Wick-rotated cycle =', r, '(su(8) needs 63)')
# Trace form on generated basis: negative definite => compact, signature (0,63).
M = np.array([real_vec(m) for m in G]).T
Q, _ = np.linalg.qr(M)  # not full if r<128; use basis subset
basis = G[:63]
T = np.array([[np.trace(basis[i]@basis[j]).real for j in range(63)] for i in range(63)])
ev = np.linalg.eigvalsh(T)
print('tr-form eigenvalues: max =', ev.max(), ' min =', ev.min(), ' => negative definite:', ev.max() < 0)
